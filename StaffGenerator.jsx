        var basicTab;
        var advancedTab;
        var staffPanel;
        var scorePanel;
        var generationPanel;
        var advancedGenerationPanel;
        var transformPanel;
        var fineStylePanel;
        var basicActions;
        var advancedActions;
        var actionControls;
        var actionGroups;
        var resetClickHandler;
        var autoAdjustClickHandler;
        var randomizeClickHandler;
        var generateClickHandler;
        var presetId;
