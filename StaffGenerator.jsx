    function beamShape(p1, p2, thickness) {
        var dx = p2[0] - p1[0];
        var dy = p2[1] - p1[1];
        var length = Math.sqrt(dx * dx + dy * dy);
        var nx;
        var ny;
        var half = thickness * 0.5;
        if (length === 0) {
            return makeAEShapeFromPoints([
                [p1[0] - half, p1[1] - half], [p1[0] + half, p1[1] - half],
                [p1[0] + half, p1[1] + half], [p1[0] - half, p1[1] + half]
            ], true);
        }
        nx = -dy / length * half;
        ny = dx / length * half;
        return makeAEShapeFromPoints([
            [p1[0] + nx, p1[1] + ny],
            [p2[0] + nx, p2[1] + ny],
            [p2[0] - nx, p2[1] - ny],
            [p1[0] - nx, p1[1] - ny]
        ], true);
    }
